"""Client requests that add, move and delete subscription links; a URL cannot be changed."""

import sqlite3
from collections.abc import Iterator
from contextlib import contextmanager
from dataclasses import replace

from ..models.application_context import ApplicationContext
from ..models.priority import PriorityError
from ..models.serialization import JsonValue
from ..models.subscription_link import SubscriptionLink
from ..request_error import ErrorCode, RequestError, expect_fields, field_value
from ..subscription_loader import SubscriptionError
from .auto_connect import on_priorities_changed
from .subscriptions import refresh_subscriptions

MODEL = "subscription_link"


@contextmanager
def _field_errors() -> Iterator[None]:
    """Report a wrong priority and a URL in use with the field they concern."""
    try:
        yield
    except PriorityError as error:
        raise RequestError(ErrorCode.VALIDATION_ERROR, str(error), {"field": "priority"}) from None
    except sqlite3.IntegrityError:
        raise RequestError(
            ErrorCode.CONFLICT, "Subscription URL is already used", {"field": "url"}
        ) from None


async def add_subscription_link(
    context: ApplicationContext, payload: dict[str, JsonValue]
) -> dict[str, JsonValue]:
    """payload: {url, priority?}; returns the id generated by the server.

    Without priority the link goes last; with one, the links from that priority
    on move down by one. Responds after all subscriptions are loaded, so the new
    link's servers reach the client first. If loading fails, the link stays saved
    and the error has code subscription_error with the new link's id and the
    failed subscription's id.
    """
    expect_fields(payload, {"url"}, {"priority"})
    url = field_value(payload, "url", str)
    if "priority" in payload:
        priority = field_value(payload, "priority", int)
    else:
        priority = len(context.settings.subscription_link.get_all()) + 1
    with _field_errors():
        link = SubscriptionLink(url=url, priority=priority)
        context.settings.subscription_link.save(link)
    await context.sync.notify(MODEL)
    # A refresh that is already running read the links before this one was saved,
    # and a new refresh does not start while it runs: wait for it, then refresh.
    await context.tasks.wait("refresh_subscriptions")
    try:
        await refresh_subscriptions(context)
    except SubscriptionError as error:
        raise RequestError(
            ErrorCode.SUBSCRIPTION_ERROR,
            "The subscription link was added, but subscriptions could not be loaded",
            {"id": link.id, "failed_id": error.subscription_id},
        ) from None
    return {"id": link.id}


async def change_subscription_link(
    context: ApplicationContext, payload: dict[str, JsonValue]
) -> dict[str, JsonValue]:
    """payload: {id, priority}; only the priority can change.

    The links between the old and new places move by one toward the old place.
    Auto connect then chooses the server again (auto_connect.on_priorities_changed);
    the same priority changes nothing.
    """
    expect_fields(payload, {"id", "priority"})
    link_id = field_value(payload, "id", str)
    priority = field_value(payload, "priority", int)
    stored = context.settings.subscription_link.get_by_id(link_id)
    if stored is None:
        raise RequestError(ErrorCode.NOT_FOUND, "Subscription link not found", {"field": "id"})
    if priority == stored.priority:
        return {}
    with _field_errors():
        context.settings.subscription_link.save(replace(stored, priority=priority))
    await context.sync.notify(MODEL)
    await on_priorities_changed(context)
    return {}


async def delete_subscription_link(
    context: ApplicationContext, payload: dict[str, JsonValue]
) -> dict[str, JsonValue]:
    """payload: {id}. The links after it move up by one.

    Servers loaded from the link stay until the next refresh; auto connect puts
    them after the servers of the stored links and chooses the server again.
    """
    expect_fields(payload, {"id"})
    if not context.settings.subscription_link.delete(field_value(payload, "id", str)):
        raise RequestError(ErrorCode.NOT_FOUND, "Subscription link not found", {"field": "id"})
    await context.sync.notify(MODEL)
    await on_priorities_changed(context)
    return {}
